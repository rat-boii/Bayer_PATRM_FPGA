"""Write model/transforms.json: the test transforms as forward parameters plus quantised b per size.

    python -m model.gen_transforms        (rewrites model/transforms.json; fails if any entry breaks D4)

Each entry: {"name", "forward": {make_b keyword arguments}, "b": {"<W>x<H>": [b11, b12, b13, b21, b22, b23]}}
b is the Q15.16 inverse mapping (D5 quantisation), valid for that output size only (the pivot is the centre).
"""

import json
import os
import sys

from model.gen_images import GRAY_SIZES
from model.patrm import check_transform, make_b

PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "transforms.json")

TRANSFORMS = [
    ("identity", {}),
    ("mirror_cols", {"mirror_cols": True}),
    ("mirror_rows", {"mirror_rows": True}),
    ("rot5", {"rot_deg": 5.0}),
    ("rot15", {"rot_deg": 15.0}),
    ("rot37", {"rot_deg": 37.0}),
    ("scale0p8", {"sx": 0.8, "sy": 0.8}),
    ("scale1p25", {"sx": 1.25, "sy": 1.25}),
    ("combined", {"rot_deg": 10.0, "sx": 0.9, "sy": 0.9, "shift": [6.5, -4.25]}),
]


def size_key(W, H):
    return f"{W}x{H}"


def build(sizes=GRAY_SIZES):
    out = []
    for name, fw in TRANSFORMS:
        kw = dict(fw)
        if "shift" in kw:
            kw["shift"] = tuple(kw["shift"])
        bs = {}
        for (W, H) in sizes:
            b = make_b(W, H, about="centre", **kw)
            check_transform(b, W, H)        # D4; raises on failure
            bs[size_key(W, H)] = list(b)
        out.append({"name": name, "forward": dict(fw, about="centre"), "b": bs})
    return out


def load(path=PATH):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)["transforms"]


def main():
    doc = {
        "note": ("Forward parameters (rotation in degrees, + = counter-clockwise as displayed; sx scales rows, "
                 "sy columns; shift = (rows, cols) in pixels; pivot = image centre) and the quantised Q15.16 "
                 "inverse coefficients b = [b11, b12, b13, b21, b22, b23] per output size W x H. "
                 "Generated by python -m model.gen_transforms."),
        "transforms": build(),
    }
    with open(PATH, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    n = sum(len(t["b"]) for t in doc["transforms"])
    print(f"gen_transforms: {len(doc['transforms'])} transforms x {len(GRAY_SIZES)} sizes = {n} entries, "
          f"all pass D4 -> {os.path.relpath(PATH)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
