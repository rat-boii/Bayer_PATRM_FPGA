"""Vectors for tb/tb_axil_regs.v (step 3.1), taken from spec/regs.json (via model/regs.py) and model/job.py.

    python scripts/gen_axil_vectors.py

Writes (data/vectors/ is not tracked; rerun this before the testbench):
  data/vectors/axil_regs_spec.hex   3 x 32 words for the 32 word slots of the 7-bit address space:
                                    words  0..31 reset value (BUILD_ID: the gray build's value),
                                    words 32..63 RW mask (bits a write may change while idle),
                                    words 64..95 kind: 0 unmapped, 1 config RW, 2 CTRL, 3 STATUS,
                                                       4 counter (RO), 5 BUILD_ID (RO)
  data/vectors/axil_regs_job.hex    word 0 = n, then n (offset, value) pairs in driver write order: the
                                    worked-example job (CLAUDE.md), gray, 640x480, BLOCK_LEN 64, IRQ_EN 1.
                                    The last pair is CTRL with START = 1.
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from model import job as J        # noqa: E402
from model import memmodel as M   # noqa: E402
from model import regs as R       # noqa: E402

OUT_DIR = ROOT / "data" / "vectors"
SPEC_HEX = OUT_DIR / "axil_regs_spec.hex"
JOB_HEX = OUT_DIR / "axil_regs_job.hex"

# Worked example (CLAUDE.md): b after D5 quantisation
WORKED_B = (52429, -39322, 131072, 39322, 52429, 65536)
JOB_W, JOB_H, JOB_BLOCK_LEN = 640, 480, 64

# Gray build (spec/interface.md section 0)
BUILD = dict(VERSION=R.VERSION, BUILD_TYPE=R.BUILD_TYPE["GRAY"], MODES=1 << R.MODE["GRAY"],
             BLOCK_LEN_MAX=M.BLOCK_LEN_MAX)

KIND_UNMAPPED, KIND_CFG, KIND_CTRL, KIND_STATUS, KIND_COUNTER, KIND_BUILD_ID = range(6)
COUNTERS = ("CYCLES", "BYTES_RD", "BYTES_WR", "RD_STALL", "WR_STALL")


def field_mask(f):
    return ((1 << f["width"]) - 1) << f["lsb"]


def spec_words():
    nslots = 1 << (R.ADDR_BITS - 2)
    reset, rw, kind = [0] * nslots, [0] * nslots, [KIND_UNMAPPED] * nslots
    for r in R.REGISTERS:
        i = r["offset"] >> 2
        rw[i] = sum(field_mask(f) for f in r["fields"] if f["access"] == "RW")
        if r["name"] == "BUILD_ID":
            reset[i] = R.pack("BUILD_ID", **BUILD)
            kind[i] = KIND_BUILD_ID
        else:
            reset[i] = r["reset"]
            kind[i] = {"CTRL": KIND_CTRL, "STATUS": KIND_STATUS}.get(
                r["name"], KIND_COUNTER if r["name"] in COUNTERS else KIND_CFG)
        if kind[i] == KIND_CFG and rw[i] == 0:
            raise SystemExit(f"{r['name']}: config register without RW fields; update this script")
    return reset + rw + kind


def job_words():
    writes, _ = J.register_image(JOB_W, JOB_H, "gray", WORKED_B, JOB_BLOCK_LEN, irq_en=1,
                                 block_len_max=M.BLOCK_LEN_MAX)
    words = [len(writes)]
    for off, _, val in writes:
        words += [off, val]
    return words, writes


def write_hex(path, words, header):
    with open(path, "w", newline="\n") as f:
        f.write(f"// {header} (generated by scripts/gen_axil_vectors.py, do not edit)\n")
        for w in words:
            f.write(f"{w & 0xFFFFFFFF:08X}\n")


def main():
    J.check_regs_current()
    os.makedirs(OUT_DIR, exist_ok=True)
    write_hex(SPEC_HEX, spec_words(), "axil_regs spec: reset[32], rw_mask[32], kind[32]")
    words, writes = job_words()
    write_hex(JOB_HEX, words, f"worked-example job, gray {JOB_W}x{JOB_H}, BLOCK_LEN {JOB_BLOCK_LEN}")
    print(f"wrote {SPEC_HEX.relative_to(ROOT)} (BUILD_ID = 0x{R.pack('BUILD_ID', **BUILD):08X})")
    print(f"wrote {JOB_HEX.relative_to(ROOT)} ({len(writes)} writes)")
    print(J.format_image(writes))
    return 0


if __name__ == "__main__":
    sys.exit(main())
